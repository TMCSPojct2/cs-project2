class LanguageController {
  static const _prefsKey = 'nabih_is_arabic';
  static final ValueNotifier<bool> isArabic = ValueNotifier<bool>(false);

  static Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    isArabic.value = prefs.getBool(_prefsKey) ?? false;
  }

  static Future<void> setArabic(bool value) async {
    isArabic.value = value;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setBool(_prefsKey, value);
  }

  static Future<void> toggle() async {
    await setArabic(!isArabic.value);
  }

  static TextDirection get direction => isArabic.value ? TextDirection.rtl : TextDirection.ltr;

  static String text(String en, String ar) => isArabic.value ? ar : en;

  static String translateRaw(String raw) {
    if (!isArabic.value) return raw;
    return _translations[raw] ?? raw;
